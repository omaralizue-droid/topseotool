"use client"

import { useState } from "react"
import { X, Copy, Check, FileDown, Share2 } from "lucide-react"
import type { SavedAudit } from "@/lib/analyzer/types"

interface ShareModalProps {
  isOpen: boolean
  onClose: () => void
  currentAudit: SavedAudit | null
}

export function ShareModal({ isOpen, onClose, currentAudit }: ShareModalProps) {
  const [copiedUrl, setCopiedUrl] = useState(false)
  const [copiedMd, setCopiedMd] = useState(false)

  if (!isOpen || !currentAudit) return null

  const shareUrl = typeof window !== "undefined"
    ? `${window.location.origin}/?domain=${encodeURIComponent(currentAudit.domain)}&brand=${encodeURIComponent(currentAudit.brand)}`
    : `https://topseotool.net/?domain=${encodeURIComponent(currentAudit.domain)}`

  const markdownContent = [
    `# AI Search Visibility Audit: ${currentAudit.brand} (${currentAudit.domain})`,
    `Generated by TOPSEOTOOL on ${new Date(currentAudit.timestamp).toLocaleDateString()}`,
    "",
    `## Executive Scores`,
    `- **Overall AI Score**: ${currentAudit.overallScore}/100 (${currentAudit.tierLabel})`,
    `- **Technical Readiness**: ${currentAudit.readinessScore}/100`,
    `- **AI Visibility Score**: ${currentAudit.visibilityScore ?? "N/A"}/100`,
    "",
    `## Verdict`,
    `> ${currentAudit.report.verdict}`,
    "",
    `## AI Perception`,
    `${currentAudit.report.perception}`,
    "",
    `## Top Recommended Actions`,
    ...currentAudit.report.actions.map(
      (a, i) => `${i + 1}. **${a.title}** (${a.impact.toUpperCase()} Impact, ${a.effort} effort)\n   - Why: ${a.why}\n   - Fix: ${a.how}`
    ),
    "",
    `## AI Answers Summary`,
    ...currentAudit.probes.map(
      (p) => `- [${p.intent.toUpperCase()}] "${p.question}"\n  Mentioned: ${p.mentioned ? "YES" : "NO"} | Sentiment: ${p.sentiment}\n  Sources: ${p.sources.map((s) => s.domain).join(", ") || "None"}`
    ),
  ].join("\n")

  const copyUrl = () => {
    navigator.clipboard.writeText(shareUrl)
    setCopiedUrl(true)
    setTimeout(() => setCopiedUrl(false), 2000)
  }

  const copyMarkdown = () => {
    navigator.clipboard.writeText(markdownContent)
    setCopiedMd(true)
    setTimeout(() => setCopiedMd(false), 2000)
  }

  const downloadJson = () => {
    const jsonStr = JSON.stringify(currentAudit, null, 2)
    const blob = new Blob([jsonStr], { type: "application/json" })
    const url = URL.createObjectURL(blob)
    const a = document.createElement("a")
    a.href = url
    a.download = `topseotool-${currentAudit.domain}-audit.json`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  const downloadMarkdown = () => {
    const blob = new Blob([markdownContent], { type: "text/markdown" })
    const url = URL.createObjectURL(blob)
    const a = document.createElement("a")
    a.href = url
    a.download = `topseotool-${currentAudit.domain}-report.md`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-xs animate-in fade-in duration-200">
      <div className="relative w-full max-w-lg bg-white rounded-2xl border border-neutral-200 shadow-xl overflow-hidden">
        {/* Header */}
        <div className="p-5 border-b border-neutral-100 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Share2 className="w-4 h-4 text-blue-600" />
            <h3 className="text-base font-bold text-neutral-900">
              Share Audit Report
            </h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="w-8 h-8 rounded-lg text-neutral-400 hover:text-neutral-700 hover:bg-neutral-100 flex items-center justify-center transition-colors cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Content */}
        <div className="p-5 space-y-4 text-xs">
          <div>
            <label className="block text-neutral-600 font-semibold mb-1.5">
              Shareable Direct Link
            </label>
            <div className="flex items-center gap-2">
              <input
                type="text"
                readOnly
                value={shareUrl}
                className="flex-1 px-3 py-2 rounded-xl border border-neutral-200 bg-neutral-50 text-neutral-700 font-mono text-[11px] truncate focus:outline-none"
              />
              <button
                type="button"
                onClick={copyUrl}
                className="px-3 py-2 rounded-xl bg-blue-600 hover:bg-blue-700 text-white font-medium flex items-center gap-1.5 cursor-pointer shrink-0 transition-colors"
              >
                {copiedUrl ? (
                  <>
                    <Check className="w-3.5 h-3.5" />
                    <span>Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy</span>
                  </>
                )}
              </button>
            </div>
          </div>

          <div className="pt-2 border-t border-neutral-100 space-y-2">
            <span className="block text-neutral-600 font-semibold">
              Export Audit Data
            </span>
            <div className="grid grid-cols-2 gap-2.5">
              <button
                type="button"
                onClick={downloadMarkdown}
                className="p-3 rounded-xl border border-neutral-200 hover:border-neutral-300 hover:bg-neutral-50 text-neutral-800 flex items-center justify-center gap-2 font-medium transition-colors cursor-pointer"
              >
                <FileDown className="w-4 h-4 text-blue-600" />
                <span>Markdown (.md)</span>
              </button>
              <button
                type="button"
                onClick={downloadJson}
                className="p-3 rounded-xl border border-neutral-200 hover:border-neutral-300 hover:bg-neutral-50 text-neutral-800 flex items-center justify-center gap-2 font-medium transition-colors cursor-pointer"
              >
                <FileDown className="w-4 h-4 text-emerald-600" />
                <span>Raw JSON (.json)</span>
              </button>
            </div>
          </div>

          <div className="pt-2">
            <button
              type="button"
              onClick={copyMarkdown}
              className="w-full py-2 rounded-xl border border-neutral-200 text-neutral-700 hover:bg-neutral-50 text-center font-medium transition-colors cursor-pointer flex items-center justify-center gap-1.5"
            >
              {copiedMd ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-600" />
                  <span className="text-emerald-700">Copied Markdown to Clipboard</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-neutral-500" />
                  <span>Copy Full Executive Report to Clipboard</span>
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  )
}
